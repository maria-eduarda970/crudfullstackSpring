package com.exemplo.turmaservice.dto;

public class Professordto {

    private Long id;
    private String nome;

    public Professordto() {
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }
}
